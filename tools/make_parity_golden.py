#!/usr/bin/env python3
"""Write test/data/arm01_parity.json, the golden file for C++/Python model parity.

The ArmController computes gravity in C++ (GravityModel, src/gravity_model.cpp)
while the sim and the calibration procedures compute it in Python (ArmModel,
arm_stack/model/robot.py). Both layer the calibration file on the URDF; this
script makes a calibration that exercises every layer, evaluates the Python
model on it at random poses, and stores inputs and outputs:

  * link_inertials: mass + COM, COM only (mass from link_masses_kg), and an
    entry for a link no driven joint owns (wrist_crank, merged into link5 by
    the locked mimic joints: both sides must ignore it),
  * link_masses_kg (weighed masses, the controller's link_mass_names/values),
  * friction for every joint,
  * kinematic_overlay entries with dxyz + drot and with dxyz only,
  * per pose: q, gravity (calibrated and nominal), FK of tool0 and flange.

test/test_gravity_parity.cpp loads the URDF and this calibration into
GravityModel and asserts the same numbers to 1e-9; test/arm_stack/
test_parity_golden.py asserts the Python model still reproduces the file.
Regenerate after changing the URDF or either model:

  python3 tools/make_parity_golden.py
"""

import argparse
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from arm_stack.config import load_arm  # noqa: E402
from arm_stack.model.robot import ArmModel  # noqa: E402

URDF = 'urdf/arm01/arm01.urdf'
FRAMES = ('tool0', 'flange')
SEED = 20261114
N_POSES = 25


def make_calibration(model: ArmModel, rng):
    links = model.link_names()
    inertials, masses = {}, {}
    for k, (link, j) in enumerate(zip(links, model.jid)):
        I = model.model.inertias[j]
        com = (np.asarray(I.lever) + rng.uniform(-0.01, 0.01, 3)).tolist()
        mass = float(I.mass * rng.uniform(0.8, 1.2))
        if k == len(links) - 1:
            masses[link] = mass                      # weighed only, no stage-5 entry
        elif k == 2:
            inertials[link] = {'mass_kg': None, 'com_m': com}   # mass from the weighed table
            masses[link] = mass
        elif k == 1:
            inertials[link] = {'mass_kg': mass, 'com_m': [com[0], None, com[2]]}  # partial COM: kept
        else:
            inertials[link] = {'mass_kg': mass, 'com_m': com}
    masses[links[0]] = float(model.model.inertias[model.jid[0]].mass * 0.5)  # overridden by mass_kg
    # not the child link of a driven joint: merged into link5, both sides skip it
    inertials['wrist_crank'] = {'mass_kg': 0.5, 'com_m': [0.01, 0.02, 0.03]}
    friction = {n: {'coulomb_nm': float(rng.uniform(0.05, 0.5)),
                    'viscous_nm_s_per_rad': float(rng.uniform(0.01, 0.1))} for n in model.joint_names}
    overlay = {}
    for n in ('shoulder_roll', 'elbow', 'wrist_pitch', 'wrist_yaw'):
        overlay[n] = {'dxyz': rng.uniform(-0.002, 0.002, 3).tolist(),
                      'drot': rng.uniform(-0.01, 0.01, 3).tolist()}
    overlay['forearm_yaw'] = {'dxyz': rng.uniform(-0.002, 0.002, 3).tolist()}
    cal = {'version': 0, 'link_inertials': inertials, 'friction': friction,
           'kinematic_overlay': overlay}
    return cal, masses


def pose(M):
    return {'translation': np.asarray(M.translation).tolist(),
            'rotation': np.asarray(M.rotation).tolist()}


def make(seed: int = SEED, n_poses: int = N_POSES):
    arm = load_arm('config/arms/arm01.yaml')
    urdf = os.path.join(ROOT, URDF)
    nominal = ArmModel(urdf, arm.names)
    rng = np.random.default_rng(seed)
    cal, masses = make_calibration(nominal, rng)
    model = ArmModel(urdf, arm.names)
    model.apply_calibration(cal, masses)
    poses = [np.zeros(model.n)] + [rng.uniform(model.lower, model.upper) for _ in range(n_poses)]
    cases = []
    for q in poses:
        cases.append({
            'q': q.tolist(),
            'gravity': model.gravity(q).tolist(),
            'gravity_nominal': nominal.gravity(q).tolist(),
            'fk': {f: pose(model.fk(q, f)) for f in FRAMES},
        })
    return {
        'note': 'generated by tools/make_parity_golden.py; checked by test/test_gravity_parity.cpp',
        'seed': seed,
        'urdf': URDF,
        'joints': list(arm.names),
        'gravity': [0.0, 0.0, -9.81],
        'calibration': cal,
        'link_masses_kg': masses,
        'coulomb': model.coulomb.tolist(),
        'viscous': model.viscous.tolist(),
        'cases': cases,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default=os.path.join(ROOT, 'test', 'data', 'arm01_parity.json'))
    ap.add_argument('--seed', type=int, default=SEED)
    args = ap.parse_args()
    golden = make(args.seed)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w') as f:
        json.dump(golden, f, indent=1)
        f.write('\n')
    print('wrote %s: %d poses' % (args.out, len(golden['cases'])))


if __name__ == '__main__':
    main()
